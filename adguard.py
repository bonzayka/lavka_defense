_RE_CSAM_NORM = [re.compile(p, re.I | re.S) for p in PATTERNS_CSAM_NORM]
_RE_CSAM_COND = [re.compile(p, re.I) for p in PATTERNS_CSAM_CONDENSED]
_RE_18 = [re.compile(p, re.I | re.S) for p in PATTERNS_18_PLUS]
_RE_JOB = [re.compile(p, re.I | re.S) for p in PATTERNS_JOB_SCAM]


def strip_quotes(raw: str) -> str:
    """Удаляет цитируемые строки (начинающиеся с >), чтобы не наказывать людей, обсуждающих спам."""
    lines = [l for l in raw.split("\n") if not l.strip().startswith(">")]
    return " ".join(lines)


def check_spam(raw: str) -> tuple[bool, str]:
    """
    Проверяет текст на детское порно/ЦП (CSAM), 18+ спам-байтинг и рекламу заработка/скама.
    Возвращает (is_spam: bool, reason: str).
    """
    if not raw:
        return False, ""
    
    clean_text = strip_quotes(raw).strip()
    if not clean_text:
        return False, ""
    
    norm = normalize_ad(clean_text)
    condensed = re.sub(r"[\s\-_.*+~#@!?,:;]+", "", norm)
    condensed_raw = re.sub(r"[\s\-_.*+~#@!?,:;]+", "", clean_text.lower())

    # 0. Детское порно / ЦП (CSAM) — наивысший приоритет
    for rx in _RE_CSAM_COND:
        if rx.search(condensed) or rx.search(condensed_raw):
            return True, "детское порно / ЦП (CSAM)"
    for rx in _RE_CSAM_NORM:
        if rx.search(norm) or rx.search(clean_text):
            return True, "детское порно / ЦП (CSAM)"

    # 1. 18+ зазывалы и вирт-боты
    for rx in _RE_18:
        if rx.search(norm) or rx.search(clean_text):
            return True, "18+ спам/зазывала"

    # 2. Реклама заработка, отзывов, легких денег
    for rx in _RE_JOB:
        if rx.search(norm) or rx.search(clean_text):
            return True, "реклама/спам заработка"

    return False, ""
