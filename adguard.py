# Расширенные гомоглифы (включая латинские u, i, d, n и спецсимволы, без цифр)
HOMOGLYPHS_AD = {
    "a": "а", "b": "в", "c": "с", "d": "д", "e": "е", "h": "н", "k": "к", "m": "м",
    "n": "н", "o": "о", "p": "р", "t": "т", "x": "х", "y": "у", "z": "з",
    "u": "и", "i": "и", "@": "а", "$": "с",
}
_TRANS_AD = str.maketrans(HOMOGLYPHS_AD)
_ZERO_WIDTH = re.compile(r"[\u200b-\u200f\u202a-\u202e\u2060\ufeff]")
_LEET_0 = re.compile(r"(?<=[а-яa-z])0(?=[а-яa-z])|(?<=[а-яa-z])0\b|\b0(?=[а-яa-z])", re.I)
_LEET_1 = re.compile(r"(?<=[а-яa-z])1(?=[а-яa-z])|(?<=[а-яa-z])1\b|\b1(?=[а-яa-z])", re.I)
_LEET_3 = re.compile(r"(?<=[а-яa-z])3(?=[а-яa-z])|(?<=[а-яa-z])3\b|\b3(?=[а-яa-z])", re.I)

def normalize_ad(text: str) -> str:
    """Очистка невидимок, нижний регистр, замена гомоглифов и внутрисловного leetspeak."""
    if not text:
        return ""
    text = _ZERO_WIDTH.sub("", text.lower())
    text = text.translate(_TRANS_AD)
    text = _LEET_0.sub("о", text)
    text = _LEET_1.sub("и", text)
    text = _LEET_3.sub("з", text)
    return text


